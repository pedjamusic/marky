"""Generate the portable inline tables from pinned, local upstream files."""

import argparse
import hashlib
import json
from functools import cache
from pathlib import Path


DATA_DIR = Path(__file__).resolve().parents[1] / "core" / "src" / "generated"
UNICODE_VERSION = "17.0.0"
SHA256 = {
    "entities.json": "d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6",
    "UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
    "SpecialCasing.txt": "efc25faf19de21b92c1194c111c932e03d2a5eaf18194e33f1156e96de4c9588",
    "PropList.txt": "130dcddcaadaf071008bdfce1e7743e04fdfbc910886f017d9f9ac931d8c64dd",
}


def pinned_text(path):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256[path.name]:
        raise ValueError(f"Unexpected SHA-256 for {path}")
    return data.decode("utf-8")


def header(filename, source, body):
    guard = f"MARKY_GENERATED_{filename.upper()}_H"
    return (
        f"// Generated by tools/generate_inline_data.py from {source}.\n"
        "// See core/README.md and Marky/ThirdPartyNotices.txt.\n"
        f"#ifndef {guard}\n#define {guard}\n\n{body}\n#endif\n"
    )


def entity_table(source):
    entries = []
    for reference, entity in json.loads(source).items():
        if not reference.endswith(";"):
            continue
        name = reference[1:-1]
        codepoints = entity["codepoints"]
        value = "".join(chr(scalar) for scalar in codepoints)
        if value != entity["characters"]:
            raise ValueError(f"Inconsistent upstream characters for {reference}")
        utf8 = "".join(f"\\x{byte:02x}" for byte in value.encode("utf-8"))
        entries.append((name, utf8))
    entries_text = "\n".join(f'    {{"{name}", "{value}"}},' for name, value in sorted(entries))
    return header("NamedEntities", "WHATWG HTML entities.json", f"""#include <string_view>

namespace marky {{

struct NamedEntity {{
    std::string_view name;
    std::string_view text;
}};

inline constexpr NamedEntity named_entities[] = {{
{entries_text}
}};

}}
""")


def property_records(source):
    for line in source.splitlines():
        record = line.split("#", 1)[0].strip()
        if record:
            yield [field.strip() for field in record.split(";")]


def unicode_tables(unicode_data, special_casing, properties):
    lowercase = {}
    canonical = {}
    combining = {}
    for line in unicode_data.splitlines():
        fields = line.split(";")
        scalar = int(fields[0], 16)
        if fields[3] != "0":
            combining[scalar] = int(fields[3])
        decomposition = fields[5]
        if decomposition and not decomposition.startswith("<"):
            canonical[scalar] = tuple(int(value, 16) for value in decomposition.split())
        if fields[13]:
            lowercase[scalar] = (int(fields[13], 16),)

    # Swift lowercases each scalar independently. Locale and context rules do not apply.
    for codepoint, lower, _title, _upper, condition, *_ in property_records(special_casing):
        scalar = int(codepoint, 16)
        mapping = tuple(int(value, 16) for value in lower.split())
        if not condition and mapping != (scalar,):
            lowercase[scalar] = mapping

    @cache
    def decompose(scalar):
        if scalar not in canonical:
            return (scalar,)
        return tuple(part for value in canonical[scalar] for part in decompose(value))

    def mappings(rows):
        for scalar, values in sorted(rows.items()):
            if len(values) > 4:
                raise ValueError(f"Mapping for U+{scalar:04X} exceeds the C++ table width")
            sequence = ", ".join(hex(value) for value in values)
            yield f"    {{{scalar:#x}, {{{sequence}}}, {len(values)}}},"

    # Foundation's CharacterSet.whitespacesAndNewlines also splits on U+200B.
    whitespace = {0x200B}
    for codepoints, prop in property_records(properties):
        if prop == "White_Space":
            start, _, end = codepoints.partition("..")
            whitespace.update(range(int(start, 16), int(end or start, 16) + 1))
    ranges = []
    for scalar in sorted(whitespace):
        if ranges and ranges[-1][1] + 1 == scalar:
            ranges[-1] = (ranges[-1][0], scalar)
        else:
            ranges.append((scalar, scalar))

    whitespace_text = "\n".join(f"    {{{first:#x}, {last:#x}}}," for first, last in ranges)
    lowercase_text = "\n".join(mappings(lowercase))
    canonical_text = "\n".join(mappings({scalar: decompose(scalar) for scalar in canonical}))
    combining_text = "\n".join(f"    {{{scalar:#x}, {value}}}," for scalar, value in sorted(combining.items()))
    return header("UnicodeData", f"Unicode {UNICODE_VERSION}", f"""#include <cstdint>

namespace marky::unicode_data {{

struct ScalarRange {{
    std::uint32_t first;
    std::uint32_t last;
}};

struct Mapping {{
    std::uint32_t scalar;
    std::uint32_t values[4];
    std::uint8_t length;
}};

struct CombiningClass {{
    std::uint32_t scalar;
    std::uint8_t value;
}};

inline constexpr ScalarRange whitespace_ranges[] = {{
{whitespace_text}
}};

inline constexpr Mapping lowercase_mappings[] = {{
{lowercase_text}
}};

inline constexpr Mapping canonical_decompositions[] = {{
{canonical_text}
}};

inline constexpr CombiningClass combining_classes[] = {{
{combining_text}
}};

}}
""")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("entities", type=Path, help="pinned WHATWG entities.json")
    parser.add_argument("ucd", type=Path, help="directory containing the pinned Unicode data files")
    parser.add_argument("--check", action="store_true", help="compare against the checked-in headers")
    args = parser.parse_args()
    try:
        files = {
            "NamedEntities.h": entity_table(pinned_text(args.entities)),
            "UnicodeData.h": unicode_tables(
                pinned_text(args.ucd / "UnicodeData.txt"),
                pinned_text(args.ucd / "SpecialCasing.txt"),
                pinned_text(args.ucd / "PropList.txt"),
            ),
        }
        for filename, content in files.items():
            path = DATA_DIR / filename
            data = content.encode("ascii")
            if args.check:
                if path.read_bytes() != data:
                    parser.exit(1, f"{path} differs from the generated data\n")
            else:
                path.write_bytes(data)
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
